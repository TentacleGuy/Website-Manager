"""Lifecycle for the common stack; legacy volumes are retained for rollback."""
import json
import os
import re
import threading
from pathlib import Path
from shared_runtime import database_info, write_config, atomic

LOCK=threading.RLock()

def context():
    import operations as op
    from store import DATA, records
    with LOCK:
        path=write_config(DATA,os.environ.get('VMM_HOST_DATA',str(DATA)),records('projects'))
    return op,['docker','compose','-f',str(path)]


def sync():
    op,args=context()
    try:
        running=op.command(args+['--profile','*','ps','--services','--status','running'],timeout=20).decode().splitlines()
        for service in running:
            if re.fullmatch(r'php\d\d',service):op.command(args+['exec','-T',service,'apache2ctl','-k','graceful'],timeout=20)
    except Exception:
        raise


def ensure_database(p):
    op,args=context()
    op.command(args+['up','-d','--wait','--wait-timeout','180','db','phpmyadmin'],timeout=300)
    info=database_info(p)
    # Data goes to stdin; passwords are never command arguments.
    sql=(f"CREATE DATABASE IF NOT EXISTS `{info['database']}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n"
         f"CREATE USER IF NOT EXISTS '{info['user']}'@'%' IDENTIFIED BY '{p['db_password']}';\n"
         f"GRANT ALL PRIVILEGES ON `{info['database']}`.* TO '{info['user']}'@'%';\n")
    op.command(args+['exec','-T','db','sh','-c','exec mariadb -uroot -p"$MARIADB_ROOT_PASSWORD"'],input=sql.encode())


def exec_php(p, command, **kwargs):
    op,args=context();site='/vmm-projects/'+p['slug']+'/site'
    service='php'+p['php'].replace('.','')
    running=op.command(args+['--profile','*','ps','--services','--status','running'],timeout=20).decode().splitlines()
    if service not in running:
        op.ensure_runtime(p['php'])
        op.command(args+['up','-d','--wait','--wait-timeout','180',service],timeout=1800)
    command=[part.replace('/vmm-tools/','/vmm-projects/'+p['slug']+'/tools/') if isinstance(part,str) else part for part in command]
    return op.command(args+['exec','-T','-w',site,'-e','VMM_PROJECT_ROOT='+site,'php'+p['php'].replace('.','')]+command,**kwargs)


def transition(p,action,php=None):
    from store import DATA, db
    with LOCK:
        op,args=context();flag=DATA/'shared/state'/(p['slug']+'.enabled')
        if action=='start':
            version=php or p['php'];op.prepare(p);op.compatible(p,version);op.ensure_runtime(version);ensure_database(p)
            sync();op.command(args+['up','-d','--wait','--wait-timeout','180','php'+version.replace('.','')],timeout=1800)
            atomic(flag,'enabled\n')
            with db() as c:c.execute("UPDATE projects SET status='running',php=?,error=NULL WHERE slug=?",(version,p['slug']))
            return 'Projekt aktiviert. Gemeinsame PHP-Laufzeit bereit.'
        flag.unlink(missing_ok=True)
        with db() as c:c.execute("UPDATE projects SET status='stopped',error=NULL WHERE slug=?",(p['slug'],))
        return 'Projekt deaktiviert. Andere Projekte und gemeinsame Dienste laufen weiter.'


def rewrite_database(p):
    import operations as op
    site=op.folder(p)/'site';info=database_info(p)
    paths=[site/'configuration.php',site/'wp-config.php']
    for path in paths:
        if not path.exists():continue
        text=path.read_text()
        if path.name=='configuration.php':
            for key,value in [('host',info['host']),('user',info['user']),('db',info['database']),('password',info['password'])]:
                pattern=r'(public\s+\$'+key+r'\s*=\s*)([\'\"])(?:\\.|(?!\2).)*?\2\s*;'
                # Configuration properties generated by Joomla are simple PHP literals.
                text,n=re.subn(pattern,lambda m:m[1]+"'"+value.replace('\\','\\\\').replace("'","\\'")+"';",text)
                if n!=1:raise ValueError('Joomla-Datenbankkonfiguration nicht eindeutig: '+key)
        else:
            for key,value in [('DB_HOST',info['host']),('DB_USER',info['user']),('DB_NAME',info['database']),('DB_PASSWORD',info['password'])]:
                pattern=r"define\s*\(\s*(['\"])"+key+r"\1\s*,\s*(['\"])(?:\\.|(?!\2).)*?\2\s*\)"
                text,n=re.subn(pattern,lambda m:"define('"+key+"','"+value+"')",text)
                if n!=1:raise ValueError('WordPress-Datenbankkonfiguration nicht eindeutig: '+key)
        text=text.replace('/var/www/html','/vmm-projects/'+p['slug']+'/site')
        path.write_text(text)
    for tool in (op.folder(p)/'tools').glob('*.php'):
        if tool.name!='extract.php':tool.write_text(tool.read_text().replace('/var/www/html','/vmm-projects/'+p['slug']+'/site'))
    op.write_tools(p)


def migrate(name):
    """Import while old web workers are stopped; retain old database volume and config."""
    import operations as op
    from store import DATA, db, project
    import shutil, zipfile, time
    with LOCK:
        p=project(name)
        if p['storage']=='shared':return 'Projekt verwendet bereits gemeinsame Laufzeiten.'
        if p['storage']=='legacy':raise ValueError('Zuerst ältere Docker-Volumes als Dateiprojekt exportieren.')
        root=op.folder(p);old_args=op.write_compose(p);was_running=p['status']=='running'
        # Start only the source DB for stopped projects too, without exposing their sites.
        op.command(old_args+['up','-d','--wait','db'],timeout=300)
        op.command(old_args+['--profile','*','stop']+['php'+v.replace('.','') for v in op.PHP]+['phpmyadmin'],timeout=90)
        backup=DATA/'exports'/('shared-migration-'+name+'-'+str(int(time.time())))
        backup.mkdir(parents=True)
        try:
            dump=op.command(old_args+['exec','-T','db','sh','-c','exec mariadb-dump -uwebsite -p"$MARIADB_PASSWORD" --single-transaction --routines --triggers website'],timeout=300)
            (backup/'database.sql').write_bytes(dump);(backup/'database.sql').chmod(0o600)
            shutil.copyfile(root/'compose.json',backup/'compose.json')
            for filename in ('configuration.php','wp-config.php'):
                if (root/'site'/filename).exists():shutil.copyfile(root/'site'/filename,backup/filename)
            with zipfile.ZipFile(backup/'site.zip','w',zipfile.ZIP_DEFLATED) as archive:
                for file in (root/'site').rglob('*'):
                    if file.is_file() and not file.is_symlink():archive.write(file,str(file.relative_to(root/'site')))
            (backup/'site.zip').chmod(0o600)
            candidate={**p,'storage':'shared'};ensure_database(candidate)
            _,args=context();info=database_info(candidate)
            op.command(args+['exec','-T','db','sh','-c','exec mariadb -uroot -p"$MARIADB_ROOT_PASSWORD" "$1"','vmm',info['database']],input=dump,timeout=300)
            # Verify imported row counts for every table before changing CMS configuration.
            script="SELECT CONCAT(TABLE_NAME,':',COALESCE(TABLE_ROWS,0)) FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME"
            # Exact row counts use safe quoted identifiers, generated inside MariaDB.
            countsql="SELECT CONCAT('SELECT ',QUOTE(TABLE_NAME),' AS t, COUNT(*) AS n FROM `',REPLACE(TABLE_NAME,'`','``'),'`;') FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() ORDER BY TABLE_NAME;"
            sourcebase=old_args+['exec','-T','db','sh','-c','exec mariadb -N -uwebsite -p"$MARIADB_PASSWORD" website']
            targetbase=args+['exec','-T','db','sh','-c','exec mariadb -N -uroot -p"$MARIADB_ROOT_PASSWORD" "$1"','vmm',info['database']]
            queries=op.command(sourcebase,input=countsql.encode());before=op.command(sourcebase,input=queries);after=op.command(targetbase,input=queries)
            if before!=after:raise RuntimeError('Tabellenvergleich nach Import fehlgeschlagen; Original bleibt erhalten.')
            (backup/'verified.json').write_text(json.dumps({'table_counts_equal':True,'tables':len(before.decode().splitlines())}))
            rewrite_database(candidate)
            with db() as c:c.execute("UPDATE projects SET storage='shared',status='stopped' WHERE slug=?",(name,))
            if was_running:transition(candidate,'start')
            else:context()
            op.command(old_args+['--profile','*','stop'],timeout=90)
            return 'Auf gemeinsame Laufzeit umgestellt: '+name+'. Tabellen vollständig verglichen; alte Volumes erhalten.'
        except Exception:
            for filename in ('configuration.php','wp-config.php'):
                if (backup/filename).exists():shutil.copyfile(backup/filename,root/'site'/filename)
            with db() as c:c.execute('UPDATE projects SET storage=?,status=? WHERE slug=?',(p['storage'],'stopped',name))
            (DATA/'shared/state'/(name+'.enabled')).unlink(missing_ok=True)
            if was_running:op.transition(name,'start')
            raise


def snapshot(p):
    import time, secrets, zipfile
    import operations as op
    from store import DATA
    if p['status']!='running':raise ValueError('Projekt für die Sicherung zuerst starten.')
    with LOCK:
        _,args=context();services=op.command(args+['--profile','*','ps','--services','--status','running']).decode().splitlines()
        php=[s for s in services if re.fullmatch(r'php\d\d',s)];paused=False
        try:
            if php:op.command(args+['pause']+php);paused=True
            info=database_info(p)
            dump=op.command(args+['exec','-T','db','sh','-c','exec mariadb-dump -uroot -p"$MARIADB_ROOT_PASSWORD" --single-transaction --routines --triggers "$1"','vmm',info['database']],timeout=300)
            root=DATA/'exports';root.mkdir(exist_ok=True);target=root/(p['slug']+'-'+str(int(time.time()))+'-'+secrets.token_hex(3)+'.zip');temp=target.with_suffix('.partial')
            with zipfile.ZipFile(temp,'w',zipfile.ZIP_DEFLATED) as z:
                z.writestr('database.sql',dump);z.writestr('project.json',json.dumps({k:p[k] for k in ('slug','cms','php','version')}))
                for file in (op.folder(p)/'site').rglob('*'):
                    if file.is_file() and not file.is_symlink():z.write(file,'site/'+str(file.relative_to(op.folder(p)/'site')))
            temp.chmod(0o600);temp.rename(target);return 'Sicherung erstellt: '+target.name
        finally:
            if paused:op.command(args+['unpause']+php)


def runtime_status():
    from runtime import PHP
    import operations as op
    try:
        output=op.command(['docker','ps','--filter','label=com.docker.compose.project=vmm-runtime','--format','{{.Label "com.docker.compose.service"}}'],timeout=10).decode().splitlines()
    except Exception:output=[]
    return [{'php':v,'running':'php'+v.replace('.','') in output} for v in PHP]


def runtime_transition(version,action):
    from runtime import ports
    ports(version)
    if action not in ('start','stop'):raise ValueError('Ungültige Laufzeitaktion.')
    with LOCK:
        op,args=context();service='php'+version.replace('.','')
        if action=='start':
            op.ensure_runtime(version);op.command(args+['up','-d','--wait',service,'phpmyadmin'],timeout=1800)
        else:op.command(args+['stop',service],timeout=60)
        return 'Gemeinsames PHP '+version+' '+('gestartet.' if action=='start' else 'gestoppt. Bei erneutem Seitenaufruf wird es bedarfsgerecht gestartet.')
